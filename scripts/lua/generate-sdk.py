"""Generate host declarations from the checked-in official API tables.
Run: python scripts/lua/generate-sdk.py [--check]
"""
from pathlib import Path
import json, re, sys
ROOT = Path(__file__).resolve().parents[2]
text = (ROOT / 'resources/lua/official-api.txt').read_text(encoding='utf-8-sig')
interfaces, enums, rows, unresolved = {}, {}, [], []
owner, table = '', ''
for line in text.splitlines():
    heading = re.match(r'^\d+\.([A-Za-z][A-Za-z0-9]*)$', line)
    if heading: owner = heading[1]
    if not line.startswith('|'): continue
    cells = [c.strip() for c in line.strip('|').split('|')]
    if cells[0] in ('字段','方法','函数','枚举名'): table=cells[0]; continue
    if cells[0].startswith('Enum.') and len(cells)>=3:
        enums.setdefault(cells[0][5:], {})[cells[1]]=cells[2]; continue
    if table=='字段' and owner and len(cells)>=4 and re.fullmatch(r'[\w, ]+',cells[0]):
        for field in cells[0].split(','):
            field=field.strip(); interfaces.setdefault(owner,{})[field]={'kind':'field','name':field,'type':cells[1],'readonly':cells[2]=='只读','doc':cells[3]}
    elif '(' in cells[0] and len(cells)>=3:
        m=re.fullmatch(r'(?:(\w+)[.:])?(\w+)\((.*)\)',cells[0])
        if not m: unresolved.append(line); continue
        scope=m[1] or owner
        if scope not in ('Script','script','game','Color','Tween','TweenSequence','ServerSignal','CursorEventData') and not scope.startswith('ClientUI'): continue
        scope='Script' if scope=='script' else scope
        interfaces.setdefault(scope,{})[m[2]]={'kind':'method','name':m[2],'args':m[3],'result':cells[1],'doc':cells[2]}
# Members without complete signatures in the tables have explicit, reviewable parameter types.
param_types={'eventType':'CursorEventType','control':'ClientUIBaseControl','itemCount':'integer','index':'integer','scrollAlignType':'ScrollAlignType','name':'string', 'callback':'fun(event: CursorEventData)', 'refreshCallback':'fun(control: ClientUIBaseControl, index: integer)'}
param_types.update({'path':'string','scriptPath':'string','scriptMappingId':'integer','active':'boolean','visible':'boolean','navigationDir':'ControllerNavigationDir','navigationMode':'ControllerNavigationMode','navigationTarget':'ClientUIBaseControl?', 'fillAmount':'number','fillHorizontalType':'ImageFillHorizontalType','fillVerticalType':'ImageFillVerticalType','fillRadialType':'ImageFillRadialType','fillRadial90Type':'ImageFillRadial90Type','imageId':'integer','imageSource':'ImageSource','widthX':'number','widthY':'number','x':'number','y':'number','z':'number'})
nullable={'GetChild','FindChild','GetParent','GetClientUIControl','FindClientUIRoot','GetControllerFocus','GetScript','GetScriptByPath','InstantiateClientUIControl'}
known=set(interfaces)|set(enums)|{'ColorValue','EnumItem','Vector3Value','TweenProperties'}
def split(s):
    result=[];start=0;depth=0
    for i,c in enumerate(s):
        if c in '(<[': depth+=1
        if c in ')>]': depth-=1
        if c==',' and depth==0: result.append(s[start:i].strip());start=i+1
    if s[start:].strip(): result.append(s[start:].strip())
    return result
def typ(t):
    t=t.strip()
    if t.endswith('?'): return typ(t[:-1])+' | undefined'
    if t.endswith('[]'): return '('+typ(t[:-2])+')[]'
    if t.startswith('fun('):
        end=t.rfind(')'); ret=t[end+1:].strip().lstrip(':').strip()
        return '(this: void'+(', '+args(t[4:end]) if t[4:end] else '')+') => '+(typ(ret) if ret else 'void')
    mapped={'integer':'number','number':'number','boolean':'boolean','string':'string','any':'unknown','table':'Record<string, unknown>','—':'void','':'void','nil':'undefined'}
    if t in mapped: return mapped[t]
    if t in known: return t
    unresolved.append('type: '+t); return 'unknown'
def args(s,scope='',name=''):
    out=[]
    for p in split(s):
        if p.startswith('...'): out.append('...args: unknown[]'); continue
        k,sep,t=p.partition(':');k=k.strip()
        if not sep:
            t=param_types.get(k,'')
            if not t: unresolved.append(scope+'.'+name+' parameter '+k);t='any'
        optional=t.strip().endswith('?') or k.endswith('?')
        if scope=='ClientUIBaseControl' and k=='eventType': t='KeyEventType' if 'KeyEvent' in name else 'ControllerNavigationEventType'
        if k=='callback' and 'KeyEvent' in name: t='fun(): boolean'
        if k=='callback' and 'NavigationEvent' in name: t='fun()'
        out.append(k.rstrip('?')+('?' if optional else '')+': '+typ(t.rstrip('?')))
    return ', '.join(out)
lines=['// Generated by scripts/lua/generate-sdk.py. Do not edit by hand.', '// Source: https://act.mihoyo.com/ys/ugc/tutorial/detail/mhtakr07vej4', 'import type { LuaMultiReturn } from "./lua-primitives.js"', '', 'declare const enumBrand: unique symbol', 'export interface EnumItem<K extends string = string> { readonly Name: string; readonly FullName: string; readonly EnumType: string; readonly [enumBrand]: K }', 'declare const colorBrand: unique symbol', 'export interface ColorValue { readonly [colorBrand]: true }', 'export type RuntimeControlId = number & { readonly __gstsControlId?: "runtime" }', 'export type ControlPrefabIndex = number & { readonly __gstsControlId?: "prefab" }', 'export interface Vector3Value { x: number; y: number; z: number }', 'export type TweenProperties = Partial<Record<TweenField, number | ColorValue>>', '']
for name,members in enums.items():
    lines.append('export type '+name+' = EnumItem<"'+name+'">')
lines.append('export interface HostEnums {')
for name,members in enums.items():
    lines.append('  readonly '+name+': {')
    for member,doc in members.items(): lines.extend(['    /** '+doc.replace('*/','* /')+' */','    readonly '+member+': '+name]);rows.append('Enum.'+name+'.'+member)
    lines.append('  }')
lines.append('}')
tween=[]
for scope,members in interfaces.items():
    if scope=='EnumItem': continue
    export_name={'game':'HostGame','Color':'HostColor'}.get(scope,scope)
    parent=' extends ClientUIBaseControl' if scope.startswith('ClientUI') and scope!='ClientUIBaseControl' else ''
    lines.append('export interface '+export_name+parent+' {')
    for name,item in members.items():
        rows.append(scope+'.'+name)
        doc=item['doc'].replace('*/','* /')
        if name=='GetClientUIControl': doc+=' 参数是运行时 id，不是编辑器的控件索引。'
        if name=='prefabIndex': doc+=' 编辑器控件/模板索引，用于模板实例化，不是运行时 id。'
        if scope=='Script' and name=='GetParam': doc+=' 返回值需检查类型；实测未观察到控件索引自动转对象，不作隐式转换。'
        lines.append('  /** '+doc+' */')
        if item['kind']=='field':
            t=typ(item['type'])
            if scope=='Script' and name=='object': t='ClientUIBaseControl'
            if scope=='ClientUIBaseControl' and name=='id': t='RuntimeControlId'
            if name=='prefabIndex': t='ControlPrefabIndex'
            if name=='parent': t='ClientUIBaseControl | undefined'
            if 'Tweenable' in doc: tween.append(name)
            lines.append('  '+('readonly ' if item['readonly'] else '')+name+': '+t)
        else:
            a=args(item['args'],scope,name)
            r=item['result']
            if r=='navigationMode, navigationTarget': r='LuaMultiReturn<[ControllerNavigationMode, ClientUIBaseControl | undefined]>'
            elif re.fullmatch(r'[xyz](?:, [xyz])+',r): r='LuaMultiReturn<['+', '.join(['number']*len(r.split(',')))+']>'
            elif re.fullmatch(r'[\w, ]+: number',r): r='LuaMultiReturn<['+', '.join(['number']*len(r.split(':')[0].split(',')))+']>'
            else: r=typ(r)
            if name in nullable and r!='unknown': r+=' | undefined'
            if scope=='Script' and name=='Invoke': r='LuaMultiReturn<unknown[]>';doc+=' 实测可返回多个值。'
            if name in ('AddVector3','AddVector3List'): a='value: '+('Vector3Value[]' if name.endswith('List') else 'Vector3Value')
            if scope=='game' and name=='GetClientUIControl': a='controlId: RuntimeControlId'
            if scope=='game' and name=='InstantiateClientUIControl': a='controlPrefabIndex: ControlPrefabIndex, parent: ClientUIBaseControl'
            if scope=='game' and name=='Tween': a='object: ClientUIBaseControl, tweenDataTable: TweenProperties, duration: number'
            lines.append('  '+('' if scope=='Color' and name=='Color' else name)+'(this: '+('void' if scope in ('game','Color') else export_name)+(', '+a if a else '')+'): '+r)
    lines.append('}\n')
lines.append('export type TweenField = '+' | '.join(json.dumps(x) for x in sorted(set(tween))) )
controls=[x for x in interfaces if x.startswith('ClientUI')]
lines.append('export interface ControlTypes { '+'; '.join(x+': '+x for x in controls)+' }')
output='\n'.join(lines)+'\n'
coverage={'source':'https://act.mihoyo.com/ys/ugc/tutorial/detail/mhtakr07vej4','members':sorted(set(rows)),'unresolved':sorted(set(unresolved))}
for rel,data in [('src/runtime/lua-host.ts',output),('resources/lua/api-coverage.json',json.dumps(coverage,ensure_ascii=False,indent=2)+'\n')]:
    p=ROOT/rel
    if '--check' in sys.argv:
        if not p.exists() or p.read_text(encoding='utf-8')!=data: raise SystemExit(rel+' needs regeneration')
    else: p.parent.mkdir(parents=True,exist_ok=True);p.write_text(data,encoding='utf-8')
print('Host API members:',len(coverage['members']),'unresolved:',len(coverage['unresolved']))
if unresolved: print('\n'.join(coverage['unresolved']))
